/**
 * Extract localized field with fallback:
 * 1. Checks item[`${field}_${lang}`] (e.g. title_id or title_en)
 * 2. Checks standard item[field] (e.g. title)
 * 3. Checks alternate language item[`${field}_${otherLang}`]
 */
export function getLocalized<T extends Record<string, any>>(
  item: T | null | undefined,
  field: string,
  lang: Language
): string {
  if (!item) return ''
  const localizedVal = item[`${field}_${lang}`]
  if (localizedVal && typeof localizedVal === 'string' && localizedVal.trim()) {
    return localizedVal
  }
  const defaultVal = item[field]
  if (defaultVal && typeof defaultVal === 'string' && defaultVal.trim()) {
    return defaultVal
  }
  const fallbackLang = lang === 'id' ? 'en' : 'id'
  const fallbackVal = item[`${field}_${fallbackLang}`]
  if (fallbackVal && typeof fallbackVal === 'string' && fallbackVal.trim()) {
    return fallbackVal
  }
  return ''
}
